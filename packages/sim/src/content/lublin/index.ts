/** Flat `[x0, z0, x1, z1, …]` to points. */
export const toPoints = (flat: FlatPoints): GroundPoint[] => {
  const out: GroundPoint[] = [];
  for (let i = 0; i + 1 < flat.length; i += 2) out.push({ x: flat[i]!, z: flat[i + 1]! });
  return out;
};

let landmarks: ReadonlyMap<string, readonly NearLandmark[]> | undefined;
/** The landmarks near a building its superstructure keeps off (G-050), worked out once for the city. */
const landmarksNear = (b: LublinBuildingData): readonly NearLandmark[] | undefined => (landmarks ??= nearLandmarks(LUBLIN_CHUNKS.flatMap((c) => c.buildings))).get(b.id);

/**
 * The `building` view of a building, positioned at (x, y, z); given its district, with Lublin
 * 2077's vertical layer over it (ADR-0051).
 */
export const buildingView = (b: LublinBuildingData, district?: LublinChunkData["district"]): ViewDescriptor => {
  const vertical = district ? verticalOf(b, district, landmarksNear(b)) : undefined;
  return {
    kind: "building",
    outline: toPoints(b.outline),
    height: b.height,
    levels: b.levels,
    use: b.use,
    ...(b.roof === undefined ? {} : { roof: b.roof }),
    ...(b.name === undefined ? {} : { name: b.name }),
    look: b.look,
    ...(b.plinth > 0 ? { plinth: b.plinth } : {}),
    ...(b.shopfront ? { shopfront: true as const } : {}),
    ...(b.soffit === undefined ? {} : { soffit: b.soffit }),
    ...(vertical ? { vertical } : {}),
  };
};

/** The `ground` view of a surface, positioned at the world origin (its points are world points). */
export const groundView = (g: LublinGroundData): ViewDescriptor => ({ kind: "ground", surface: g.surface, outline: toPoints(g.outline) });
/** A line of road markings (ADR-0052), positioned at the world origin. */
export const markingView = (m: LublinMarkingData): ViewDescriptor => ({ kind: "road-marking", marking: m.kind, line: toPoints(m.line) });

type Bounds = LublinChunkData["bounds"];
const EDGE = 0.05;

/** Whether `o` lies against `side` of `b` along some stretch of it. */
const against = (b: Bounds, o: Bounds, side: keyof TerrainOpenSides): boolean => {
  if (side === "south" || side === "north") {
    const z = side === "south" ? b.minZ : b.maxZ;
    const meet = side === "south" ? Math.abs(o.maxZ - z) < EDGE : Math.abs(o.minZ - z) < EDGE;
    return meet && o.maxX > b.minX + EDGE && o.minX < b.maxX - EDGE;
  }
  const x = side === "west" ? b.minX : b.maxX;
  const meet = side === "west" ? Math.abs(o.maxX - x) < EDGE : Math.abs(o.minX - x) < EDGE;
  return meet && o.maxZ > b.minZ + EDGE && o.minZ < b.maxZ - EDGE;
};

/** The sides of a chunk no other chunk of the city lies against: the edge of the map data. */
export const openSides = (c: LublinChunkData, chunks: readonly LublinChunkData[] = LUBLIN_CHUNKS): TerrainOpenSides => {
  const open = (side: keyof TerrainOpenSides) => !chunks.some((o) => o !== c && against(c.bounds, o.bounds, side));
  return { south: open("south"), north: open("north"), west: open("west"), east: open("east") };
};

/** The `terrain` view of a chunk, positioned at the world origin, with its sides at the edge of the data. */
export const terrainView = (c: LublinChunkData): ViewDescriptor => ({ kind: "terrain", grid: c.terrain, open: openSides(c) });

/**
 * Street furniture per chunk id (ADR-0047), generated by `pnpm osm:props` from
 * `docs/world/lublin-props.todo.json`: lamps, benches, trees, bollards and the rest, in world
 * metres with `y` from the chunk's terrain.
 */
export const LUBLIN_STREET_PROPS: Readonly<Record<string, readonly StreetPropItem[]>> = decodePropTable(LUBLIN_PROP_TABLE);

/** The `street-props` view of a chunk, positioned at the world origin; empty for an unknown chunk. */
export const streetPropsView = (chunkId: string): ViewDescriptor => propsViewOf(LUBLIN_STREET_PROPS[chunkId] ?? []);
