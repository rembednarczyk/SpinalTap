/** Flat `[x0, z0, x1, z1, …]` to points. */
export const toPoints = (flat: FlatPoints): GroundPoint[] => {
  const out: GroundPoint[] = [];
  for (let i = 0; i + 1 < flat.length; i += 2) out.push({ x: flat[i]!, z: flat[i + 1]! });
  return out;
};

/**
 * The `building` view of a building, positioned at (x, y, z); given its district, with Lublin
 * 2077's vertical layer over it (ADR-0051).
 */
export const buildingView = (b: LublinBuildingData, district?: LublinChunkData["district"]): ViewDescriptor => {
  const vertical = district ? verticalOf(b, district) : undefined;
  return {
    kind: "building",
    outline: toPoints(b.outline),
    height: b.height,
    levels: b.levels,
    use: b.use,
    ...(b.roof === undefined ? {} : { roof: b.roof }),
    ...(b.name === undefined ? {} : { name: b.name }),
    look: b.look,
    ...(b.plinth > 0 ? { plinth: b.plinth } : {}),
    ...(b.shopfront ? { shopfront: true as const } : {}),
    ...(vertical ? { vertical } : {}),
  };
};

/** The `ground` view of a surface, positioned at the world origin (its points are world points). */
export const groundView = (g: LublinGroundData): ViewDescriptor => ({ kind: "ground", surface: g.surface, outline: toPoints(g.outline) });

/** The `terrain` view of a chunk, positioned at the world origin. */
export const terrainView = (c: LublinChunkData): ViewDescriptor => ({ kind: "terrain", grid: c.terrain });

/**
 * Street furniture per chunk id (ADR-0047), generated by `pnpm osm:props` from
 * `docs/world/lublin-props.todo.json`: lamps, benches, trees, bollards and the rest, in world
 * metres with `y` from the chunk's terrain.
 */
export const LUBLIN_STREET_PROPS: Readonly<Record<string, readonly StreetPropItem[]>> = decodePropTable(LUBLIN_PROP_TABLE);

/** The `street-props` view of a chunk, positioned at the world origin; empty for an unknown chunk. */
export const streetPropsView = (chunkId: string): ViewDescriptor => propsViewOf(LUBLIN_STREET_PROPS[chunkId] ?? []);
