/**
 * The legs of a locomotion clip in the engine's terms (ADR-0090): the joints of both legs per
 * frame relative to the hips, in the rig body's frame (+Y up, +Z forward, the character's left at
 * -X) and in leg lengths, so any figure's legs can follow them; the hips' rise and fall; and how
 * far the clip walks in one cycle, which the root motion of a Mixamo clip carries and the game,
 * moving the character itself, takes out.
 */

export const LEG_JOINTS = ["hipL", "kneeL", "ankleL", "toeL", "hipR", "kneeR", "ankleR", "toeR"] as const;
export type LegJoint = (typeof LEG_JOINTS)[number];

/** A clip sampled at `frames` evenly spaced times over one `cycle`, positions in the rig body's frame (any unit). */
export interface RawClip {
  readonly cycle: number;
  readonly frames: number;
  readonly hips: readonly number[];
  readonly joints: Readonly<Record<LegJoint, readonly number[]>>;
  /** Where the hips are one cycle on: the start of the next loop. */
  readonly hipsEnd: readonly [number, number, number];
}

export interface LegClip {
  /** Seconds of one loop. */
  readonly cycle: number;
  readonly frames: number;
  /** Horizontal travel of the hips in one loop, in leg lengths: x to the character's right, z forward. */
  readonly stride: { readonly x: number; readonly z: number };
  /** The hips' height over its mean, per frame, in leg lengths. */
  readonly bob: readonly number[];
  /** Per frame, `LEG_JOINTS` in order, x y z relative to the hips, in leg lengths. */
  readonly legs: readonly number[];
}

const at = (a: readonly number[], f: number): [number, number, number] => [a[f * 3]!, a[f * 3 + 1]!, a[f * 3 + 2]!];
const dist = (a: readonly number[], b: readonly number[]): number => Math.hypot(a[0]! - b[0]!, a[1]! - b[1]!, a[2]! - b[2]!);

/** A leg's length at the first frame: hip to knee and knee to ankle, the mean of both legs. */
export const legLength = (raw: RawClip): number => {
  const leg = (s: "L" | "R") => dist(at(raw.joints[`hip${s}`], 0), at(raw.joints[`knee${s}`], 0)) + dist(at(raw.joints[`knee${s}`], 0), at(raw.joints[`ankle${s}`], 0));
  return (leg("L") + leg("R")) / 2;
};

const round = (v: number): number => Math.round(v * 1000) / 1000;

/** The other side of a joint: hipL <-> hipR. */
const otherSide = (j: LegJoint): LegJoint => (j.endsWith("L") ? `${j.slice(0, -1)}R` : `${j.slice(0, -1)}L`) as LegJoint;

/**
 * The clip turned left for right: x over, each leg's path given to the other, and half a loop
 * on, so that the left foot sets off when it does in the clips mixed with it.
 */
export const mirrored = (raw: RawClip): RawClip => {
  const half = Math.floor(raw.frames / 2);
  const flip = (a: readonly number[]): number[] => {
    const out: number[] = [];
    for (let f = 0; f < raw.frames; f++) {
      const [x, y, z] = at(a, (f + half) % raw.frames);
      out.push(-x, y, z);
    }
    return out;
  };
  const joints = Object.fromEntries(LEG_JOINTS.map((j) => [j, flip(raw.joints[otherSide(j)])])) as Record<LegJoint, number[]>;
  // The travel of a loop is the same whichever frame it starts at: only its x turns over.
  const hips = flip(raw.hips);
  const travel = [raw.hipsEnd[0] - raw.hips[0]!, raw.hipsEnd[1] - raw.hips[1]!, raw.hipsEnd[2] - raw.hips[2]!] as const;
  return { ...raw, hips, joints, hipsEnd: [hips[0]! - travel[0], hips[1]! + travel[1], hips[2]! + travel[2]] };
};

/** The clip in place and in leg lengths. */
export const toLegClip = (raw: RawClip): LegClip => {
  const unit = legLength(raw);
  const ys = Array.from({ length: raw.frames }, (_, f) => raw.hips[f * 3 + 1]!);
  const mean = ys.reduce((a, b) => a + b, 0) / raw.frames;
  const legs: number[] = [];
  for (let f = 0; f < raw.frames; f++) {
    const hip = at(raw.hips, f);
    for (const j of LEG_JOINTS) {
      const p = at(raw.joints[j], f);
      legs.push(round((p[0] - hip[0]) / unit), round((p[1] - hip[1]) / unit), round((p[2] - hip[2]) / unit));
    }
  }
  const start = at(raw.hips, 0);
  return {
    cycle: round(raw.cycle),
    frames: raw.frames,
    stride: { x: round((raw.hipsEnd[0] - start[0]) / unit), z: round((raw.hipsEnd[2] - start[2]) / unit) },
    bob: ys.map((y) => round((y - mean) / unit)),
    legs,
  };
};

/** The generated module of the engine's leg clips. */
export const legClipsModule = (clips: Readonly<Record<string, LegClip>>, sources: Readonly<Record<string, string>>): string => {
  const lines = [
    "// Generated by tools/animations (ADR-0090) from Mixamo clips; do not edit by hand.",
    `// Sources: ${Object.entries(sources)
      .map(([k, v]) => `${k} <- ${v}`)
      .join("; ")}.`,
    'import type { LegClip } from "./leg-clip";',
    "",
    "export const LEG_CLIPS = {",
    ...Object.entries(clips).map(([k, c]) => `  ${k}: ${JSON.stringify(c)},`),
    "} as const satisfies Readonly<Record<string, LegClip>>;",
    "",
  ];
  return lines.join("\n");
};
