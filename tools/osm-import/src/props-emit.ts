/** Writes the street furniture (ADR-0047) as a compact content table: per chunk, per kind, flat rows. */
import type { StreetPropItem } from "../../../packages/core/src/world/city-geo.ts";

/** Numbers per piece in a row of the table: x, y, z, yaw, variant. */
export const PROP_STRIDE = 5;

/** The table of one chunk: kinds in name order, pieces in placement order. */
export const propRows = (items: readonly StreetPropItem[]): [string, number[]][] => {
  const rows = new Map<string, number[]>();
  for (const i of items) {
    const row = rows.get(i.prop) ?? [];
    row.push(i.x, i.y, i.z, i.yaw, i.variant);
    rows.set(i.prop, row);
  }
  return [...rows.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1));
};

export const emitProps = (byChunk: ReadonlyMap<string, readonly StreetPropItem[]>): string =>
  [
    "// Generated by tools/osm-import (`pnpm osm:props`) from docs/world/lublin-props.todo.json and the chunks' terrain. Do not edit.",
    "// Street furniture of Lublin 2077 (ADR-0047). Positions from OpenStreetMap © OpenStreetMap contributors, ODbL 1.0 (a derived",
    "// database under the ODbL), the rest placed by the rules of the plan. See data/osm/ATTRIBUTION.md.",
    'import type { LublinPropTable } from "./types";',
    "",
    "/** Per chunk, per kind: flat rows of x, y, z (world metres), yaw (radians), variant. */",
    "export const LUBLIN_PROP_TABLE: LublinPropTable = {",
    ...[...byChunk.entries()].flatMap(([id, items]) => [`  ${JSON.stringify(id)}: {`, ...propRows(items).map(([k, row]) => `    ${JSON.stringify(k)}: ${JSON.stringify(row)},`), "  },"]),
    "};",
    "",
  ].join("\n");
