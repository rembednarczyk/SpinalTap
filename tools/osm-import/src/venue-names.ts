const BY_NAME = new Map(VENUE_NAMES.map(([osm, name, colour]) => [osm, { name, colour }]));

/** FNV-1a of a string: a generic name picked by the venue's id stays the same on every import. */
const hash = (s: string): number => {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 0x01000193) >>> 0;
  return h;
};

/**
 * A venue's 2077 name and the real sign's colour: from the table by its map name, or a generic
 * name for its kind (picked by `id`) when the map has none or the table not yet.
 */
export const venueEntry = (osm: string | undefined, kind: VenueKind, id: string): { name: string; named: boolean; color?: string } => {
  const row = osm === undefined ? undefined : BY_NAME.get(osm);
  if (row) return { name: row.name, named: true, ...(row.colour ? { color: row.colour } : {}) };
  const list = GENERIC_NAMES[kind];
  return { name: list[hash(id) % list.length]!, named: false };
};
